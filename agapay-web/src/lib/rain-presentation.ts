/**
 * A8: how confidently a rain-gauge figure may be presented. Three separate facts, each from
 * structured metadata (the same rule as the mobile app):
 *  - coverage: rainfall product quality / coverage_complete;
 *  - calibration: claimed only with a physical measured-water attestation
 *    (channel_health.calibration.physical_validation === "validated") on top of a
 *    field_reviewed, matched configuration whose hash the rain calibration version equals.
 *    A field review or configuration match alone is not physical calibration;
 *  - origin: prototype / bench_reviewed configurations are labelled as prototypes. That does
 *    not mean the tips were generated by hand: they are simply not validated as rainfall.
 * Missing metadata is never turned into a claim of verified accuracy.
 */
export type RainProduct = {
  quality?: string | null; coverage_complete?: boolean | null; tip_count?: number | null;
  mm_per_tip?: number | null; calibration_version?: string | null;
} | null | undefined;

export type RainConfiguration = {
  status?: string | null; validation_status?: string | null; config_hash?: string | null;
} | null | undefined;

export type RainPresentation = {
  title: string; badge: string | null; amountSuffix: string; coverage: string; tips: string | null;
  calibration: string; origin: string | null; calibrated: boolean; completeCoverage: boolean; caveat: string;
};

export function rainPresentation(product: RainProduct, configuration: RainConfiguration,
  physicalValidation?: string | null): RainPresentation {
  const status = configuration?.validation_status ?? null;
  const hash = configuration?.config_hash ?? null;
  const version = product?.calibration_version ?? null;
  const calibrated = physicalValidation === "validated" && status === "field_reviewed"
    && configuration?.status === "matched" && hash !== null && version !== null && version === hash;
  const completeCoverage = Boolean(product && product.coverage_complete === true && product.quality !== "partial");
  const mmPerTip = typeof product?.mm_per_tip === "number" && Number.isFinite(product.mm_per_tip) ? product.mm_per_tip : null;
  const tipCount = typeof product?.tip_count === "number" && Number.isFinite(product.tip_count) ? product.tip_count : null;
  const bench = status === "prototype" || status === "bench_reviewed";
  const conversion = mmPerTip === null ? "conversion unknown" : `${mmPerTip.toFixed(mmPerTip < 1 ? 1 : 2)} mm/tip`;
  const calibration = calibrated
    ? `Calibrated conversion: ${conversion} (measured-water validation).`
    : `Provisional conversion: ${conversion}. Not calibrated against measured water.`;
  const origin = bench ? "Prototype configuration: tips are not validated as measured rainfall."
    : calibrated ? null : "Not confirmed as measured rainfall.";
  return {
    title: calibrated ? "Rainfall Activity" : "Rain-gauge Activity",
    badge: bench ? "Prototype" : calibrated ? null : "Unvalidated",
    amountSuffix: calibrated ? "mm" : "mm rainfall-equivalent",
    coverage: !product ? "Coverage unknown" : completeCoverage ? "Complete coverage" : "Partial coverage",
    tips: tipCount === null ? null : `${tipCount} recorded tip${tipCount === 1 ? "" : "s"}`,
    calibration, origin, calibrated, completeCoverage,
    caveat: [calibration, origin].filter(Boolean).join(" "),
  };
}
